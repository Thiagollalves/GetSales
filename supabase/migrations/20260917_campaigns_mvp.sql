create table if not exists public.campaigns (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 3 and 120),
  kind text not null check (kind in ('official', 'personalized')),
  connection_id text not null,
  connection_kind text not null check (connection_kind in ('official', 'whatsmeow')),
  audience_tag text not null default 'all',
  audience_count integer not null check (audience_count > 0),
  template_id text,
  schedule_at timestamptz,
  status text not null check (status in ('DRAFT', 'SCHEDULED', 'CANCELLED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (kind <> 'official' or template_id is not null)
);

create index if not exists campaigns_status_created_at_idx on public.campaigns (status, created_at desc);
